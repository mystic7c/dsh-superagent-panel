// Builds the Web client bundle from the ordered plain-JavaScript fragments in client/src/.
// The Harness Web module loader loads one file that registers a lazy factory for this package id;
// each fragment is plain script text (no imports/exports), concatenated inside that factory, so a
// missing or reordered fragment fails loudly at `node --check`/page load rather than at runtime.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(root, 'client', 'src')
const outFile = join(root, 'client', 'index.js')
const PACKAGE = '@mlamp/dsh-superagent-ui'

const files = readdirSync(sourceDir).filter(name => name.endsWith('.js')).sort()
if (files.length === 0) throw new Error('client/src has no fragments')

const body = files.map(name => {
  const text = readFileSync(join(sourceDir, name), 'utf8').trimEnd()
  return `\n// ---- ${name} ----\n${text}\n`
}).join('\n')

const banner = `// Generated by scripts/build-client.mjs from client/src/*.js — do not edit by hand.
// Registers the Superagent management panel: sidebar icon in \`sidebar.panellist\` and the full
// management panel in the keyed \`main\` slot. Plain React only; data comes from the host half over
// same-origin \`/superagent/api\` routes.`
const prelude = `
const { useState, useEffect, useRef, useMemo, useCallback, useLayoutEffect, useContext, createContext, Fragment } = React
const h = React.createElement
`
const output = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE)},
  factory(require) {
    const React = require('react')
${prelude}${body}
    return { inject, apply }
  },
})
`

if (process.argv.includes('--check')) {
  const current = (() => { try { return readFileSync(outFile, 'utf8') } catch { return undefined } })()
  if (current !== output) {
    console.error('client/index.js is out of date; run `node scripts/build-client.mjs`')
    process.exit(1)
  }
  console.log(`client/index.js is up to date (${files.length} fragments)`)
} else {
  writeFileSync(outFile, output)
  console.log(`wrote ${outFile} (${files.length} fragments, ${output.split('\n').length} lines)`)
}
